"""Dynamic version information from package metadata and git.

This module provides version information with the following fallback chain:
- __version__: Package metadata → pyproject.toml → "unknown"
- __released__: Build-time ``_release_info.py`` → SDK repo's latest git tag date → "unreleased"
"""

__all__ = ["__version__", "__released__"]

# Distribution name on PyPI (differs from the import package name "solarfarmer")
_DISTRIBUTION_NAME = "dnv-solarfarmer"


def _get_version():
    """Get version from package metadata, fallback to pyproject.toml for development.

    Returns:
        str: Version string (e.g., "0.1.0") or "unknown" if unavailable.
    """
    # First try: installed package metadata (pip install)
    try:
        from importlib.metadata import version

        return version(_DISTRIBUTION_NAME)
    except Exception:
        pass

    # Second try: development mode - read from pyproject.toml
    try:
        from pathlib import Path

        pyproject_path = Path(__file__).parents[1] / "pyproject.toml"

        # Try Python 3.11+ tomllib first
        try:
            import tomllib

            with pyproject_path.open("rb") as f:
                data = tomllib.load(f)
            return data["project"]["version"]
        except ImportError:
            # Fallback for Python 3.10: simple regex parsing
            import re

            with pyproject_path.open(encoding="utf-8") as f:
                content = f.read()
            match = re.search(r'^\s*version\s*=\s*["\']([^"\']+)["\']', content, re.MULTILINE)
            if match:
                return match.group(1)
    except Exception:
        pass

    return "unknown"


def _get_release_date():
    """Get the release date of the installed SDK.

    Released wheels ship a ``_release_info.py`` module generated by the release
    workflow. For source checkouts, the date of the latest tag in the SDK's own
    git repository is used instead.

    Returns:
        str: ISO date string (YYYY-MM-DD) of the release,
             or "unreleased" if it cannot be determined (development mode).
    """
    try:
        from ._release_info import RELEASE_DATE

        return RELEASE_DATE
    except ImportError:
        pass

    import subprocess
    from pathlib import Path

    repo_root = Path(__file__).resolve().parents[1]
    try:
        # Only trust git if the package lives in its own checkout; otherwise an
        # install inside an unrelated repo would report that repo's tag dates.
        toplevel = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
            check=False,
            timeout=2,
            cwd=repo_root,
        )
        if toplevel.returncode != 0 or Path(toplevel.stdout.strip()).resolve() != repo_root:
            return "unreleased"

        result = subprocess.run(
            ["git", "log", "-1", "--format=%cs", "--tags", "--no-walk"],
            capture_output=True,
            text=True,
            check=False,
            timeout=2,
            cwd=repo_root,
        )
        if result.returncode == 0 and result.stdout.strip():
            return result.stdout.strip()
    except Exception:
        pass

    return "unreleased"

__version__ = _get_version()
__released__ = _get_release_date()
